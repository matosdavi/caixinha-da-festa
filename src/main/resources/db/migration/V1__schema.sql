-- Schema da caixinha (seção 2 da especificação).
-- Roda igual no PostgreSQL (Neon) e no H2 em modo PostgreSQL (dev e testes).
-- Regras de ouro:
--   * dinheiro é sempre NUMERIC(12,2), nunca ponto flutuante;
--   * o saldo NUNCA é guardado: é sempre calculado a partir de "lancamento";
--   * meses (YearMonth) são guardados como texto 'AAAA-MM'.

-- Configuração: uma única linha (id = 1).
CREATE TABLE caixinha (
    id                         BIGINT        PRIMARY KEY CHECK (id = 1),
    nome                       VARCHAR(100)  NOT NULL,
    mes_inicio                 VARCHAR(7)    NOT NULL,
    mes_fim                    VARCHAR(7)    NOT NULL,
    data_festa                 DATE,
    margem_imprevistos         NUMERIC(5,4)  NOT NULL DEFAULT 0.10 CHECK (margem_imprevistos >= 0),
    cota_base                  NUMERIC(12,2) CHECK (cota_base >= 0),
    data_fechamento_lista      DATE          NOT NULL,
    chave_pix                  VARCHAR(77),
    nome_recebedor             VARCHAR(25),
    cidade_recebedor           VARCHAR(15),
    desconto_novembro_por_peso NUMERIC(12,2) CHECK (desconto_novembro_por_peso >= 0),
    CHECK (mes_inicio <= mes_fim)
);

CREATE TABLE pessoa (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(80)  NOT NULL,
    -- E.164 sem '+', ex.: 5511999998888
    telefone       VARCHAR(15),
    peso           NUMERIC(3,2) NOT NULL CHECK (peso IN (0.00, 0.50, 1.00)),
    -- quem recebe o link e paga pela pessoa (nulo = ela mesma)
    responsavel_id BIGINT REFERENCES pessoa (id),
    data_entrada   DATE         NOT NULL,
    ativo          BOOLEAN      NOT NULL DEFAULT TRUE,
    observacao     VARCHAR(500),
    CHECK (responsavel_id IS NULL OR responsavel_id <> id)
);

CREATE TABLE item_orcamento (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria      VARCHAR(30)   NOT NULL CHECK (categoria IN ('ALUGUEL', 'LIMPEZA', 'COMIDA', 'BEBIDA',
                                     'GELO_CARVAO_DESCARTAVEIS', 'DECORACAO', 'TRANSPORTE', 'OUTROS')),
    descricao      VARCHAR(200)  NOT NULL,
    valor_previsto NUMERIC(12,2) NOT NULL CHECK (valor_previsto >= 0),
    valor_real     NUMERIC(12,2) CHECK (valor_real >= 0)
);

CREATE TABLE lancamento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo            VARCHAR(25)   NOT NULL CHECK (tipo IN ('DEPOSITO', 'RENDIMENTO', 'DOACAO', 'GASTO',
                                      'DEVOLUCAO', 'CREDITO_ANO_ANTERIOR')),
    pessoa_id       BIGINT        REFERENCES pessoa (id),
    -- sempre positivo: o tipo diz se entra ou sai
    valor           NUMERIC(12,2) NOT NULL CHECK (valor > 0),
    data            DATE          NOT NULL,
    descricao       VARCHAR(200),
    categoria       VARCHAR(30)   CHECK (categoria IN ('ALUGUEL', 'LIMPEZA', 'COMIDA', 'BEBIDA',
                                      'GELO_CARVAO_DESCARTAVEIS', 'DECORACAO', 'TRANSPORTE', 'OUTROS')),
    comprovante_url VARCHAR(500),
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- DEPOSITO, DEVOLUCAO e CREDITO_ANO_ANTERIOR são de uma pessoa; os outros, da caixinha
    CHECK ((tipo IN ('DEPOSITO', 'DEVOLUCAO', 'CREDITO_ANO_ANTERIOR')) = (pessoa_id IS NOT NULL)),
    -- categoria só existe (e é obrigatória) para GASTO
    CHECK ((tipo = 'GASTO') = (categoria IS NOT NULL))
);
CREATE INDEX idx_lancamento_pessoa ON lancamento (pessoa_id);

CREATE TABLE link_acesso (
    -- 128 bits de SecureRandom em base64url (22 caracteres)
    token     VARCHAR(32) PRIMARY KEY,
    pessoa_id BIGINT      NOT NULL REFERENCES pessoa (id),
    ativo     BOOLEAN     NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_link_acesso_pessoa ON link_acesso (pessoa_id);

CREATE TABLE aviso_mensal (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mes        VARCHAR(7)  NOT NULL,
    -- nulo nos avisos para o GRUPO
    pessoa_id  BIGINT      REFERENCES pessoa (id),
    tipo       VARCHAR(10) NOT NULL CHECK (tipo IN ('INDIVIDUAL', 'GRUPO')),
    avisado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((tipo = 'INDIVIDUAL') = (pessoa_id IS NOT NULL))
);
CREATE INDEX idx_aviso_mensal_mes ON aviso_mensal (mes);

CREATE TABLE escolha_sobra (
    pessoa_id     BIGINT      PRIMARY KEY REFERENCES pessoa (id),
    opcao         VARCHAR(10) NOT NULL CHECK (opcao IN ('DEVOLVER', 'CREDITO')),
    registrada_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
